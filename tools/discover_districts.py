SLUGS = {
    "recruitment": {"recruitment", "भर्ती"},
    "announcements": {"announcements", "घोषणाएँ", "घोषणाएं"},
}
FALLBACK_PATHS = {
    "recruitment": ["/en/notice_category/recruitment/", "/notice_category/recruitment/",
                    "/notice_category/भर्ती/"],
    "announcements": ["/en/notice_category/announcements/", "/notice_category/announcements/",
                      "/notice_category/घोषणाएँ/", "/notice_category/घोषणाएं/"],
}


def _homepage_links(base: str) -> dict[str, list[str]]:
    found = {cat: [] for cat in SLUGS}
    resp = get(base + "/", timeout=25)
    if not resp.ok:
        return found
    for a in BeautifulSoup(resp.text, "lxml").find_all("a", href=True):
        href = urljoin(base + "/", a["href"])
        if "notice_category/" not in href or not href.startswith(base):
            continue
        slug = unquote(href.rstrip("/").rsplit("/", 1)[-1]).lower()
        for cat, names in SLUGS.items():
            if slug in names and href not in found[cat]:
                found[cat].append(href)
    return found


def _first_valid(urls: list[str]) -> tuple[str | None, str]:
    probe = Source(id="probe", name="probe", kind="s3waas", url="")
    results = fetch_many(urls, workers=4, timeout=25)
    for url in urls:
        r = results[url]
        if r.ok:
            status = s3waas.parse(r.text, url, probe).status
            if status in ("ok", "empty"):
                return url, status
    return None, "not found"


def discover(name: str, base: str) -> dict:
    links = _homepage_links(base)
    entry = {"district": name, "base": base}
    for cat in SLUGS:
        candidates = links[cat] + [base + p for p in FALLBACK_PATHS[cat]]
        # Prefer the English page when both exist: titles are easier to classify.
        candidates.sort(key=lambda u: "/en/" not in u)
        url, status = _first_valid(list(dict.fromkeys(candidates)))
        entry[cat] = url
        print(f"  {name:32} {cat:13} {status:9} {url or '-'}")
    return entry


def main():
    entries = [discover(n, b) for n, b in CG_DISTRICTS.items()]
    out = SOURCES_DIR / "s3waas_districts.yaml"
    header = ("# Chhattisgarh district websites (NIC S3WaaS). Generated by tools/discover_districts.py;\n"
              "# safe to edit by hand. `announcements` is scanned too, keeping job-related rows only.\n")
    out.write_text(header + yaml.safe_dump(entries, allow_unicode=True, sort_keys=False), encoding="utf-8")
    missing = [e["district"] for e in entries if not e["recruitment"]]
    print(f"\nWrote {out} — {len(entries) - len(missing)}/{len(entries)} recruitment pages found.")
    if missing:
        print("Missing:", ", ".join(missing))


if __name__ == "__main__":
    main()
